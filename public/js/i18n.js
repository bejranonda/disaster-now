/** t("key", {q: …}) in the current language, with {name} placeholders filled. */
export function makeT(lang) {
  return (key, vars = {}) => {
    const s = STR[key] ? STR[key][lang === "en" ? "en" : "th"] : key;
    return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
  };
}

